import React, { useEffect, useRef } from "react";
import './LorePage.css';

function LorePage() {
    const sectionsRef = useRef([]);

    useEffect(() => {
        const observedElements = sectionsRef.current;
        const observer = new IntersectionObserver(
            (entries) => {
                entries.forEach((entry) => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('visible');
                        observer.unobserve(entry.target);
                    }
                });
            },
            {
                threshold: 0.1 
            }
        );
        observedElements.forEach((section) => {
            if (section) {
                observer.observe(section);
            }
        });
        return () => {
            observedElements.forEach((section) => {
                if (section) {
                    observer.unobserve(section);
                }
            });
        };
    }, []);

    return (
        <main className="lore-page">
            <h1 className="lore-title">Лор проекта “Polynochnyj Project”</h1>
            {/* --- Секция 1: Предыстория --- */}
            <section className="lore-section" ref={(el) => (sectionsRef.current[0] = el)}>
                <h2>Предыстория</h2>
                <p>
                    До трагедии Чернобыля этот край был живым сердцем советской Украины. Молодая Припять, основанная в 1970 году, задумывалась как “город будущего” — образец для всей страны. Её проектировали лучшие архитекторы Союза: прямые проспекты, панельные дома с мозаичными узорами, зелёные дворы, школы, детские сады, и дворец культуры “Энергетик”.
                </p>
                <p>
                    Припять строилась как витрина социализма. Газеты писали: “Атом — в каждый дом!”. Сюда приезжали инженеры, военные, врачи и учителя. Неподалеку возвышалась Чернобыльская АЭС — бетонный и стальной великан, храм прогресса. Радио и плакаты твердили: “РБМК-1000 — реактор XXI века!”.
                </p>
                <p>
                    Но за этой витриной скрывались мелкие тревоги. Рабочие станции иногда говорили о сбоях, инженеры спорили о надёжности конструкций. В протоколах появлялись строчки о “несовершенстве систем”, но эти слова тонули в океане оптимизма. Никто и подумать не мог, что улицы, по которым они спешили на работу, вскоре превратятся в безмолвные коридоры.
                </p>
            </section>

            {/* --- Секция 2: Трагедия 1986 года --- */}
            <section className="lore-section" ref={(el) => (sectionsRef.current[1] = el)}>
                <h2>Трагедия 1986 года</h2>
                <p>
                    26 апреля 1986 года, в час с небольшим после полуночи, четвертый энергоблок Чернобыльской АЭС проводил эксперимент. Цепочка ошибок и просчетов запустила необратимый процесс. В 00:23:47 реактор вышел из-под контроля. Спустя мгновение земля содрогнулась от взрыва, выбросив наружу тысячи тонн радиоактивного топлива.
                </p>
                <p>
                    Над станцией встал столб огня, подсвеченный странным, завораживающим голубоватым свечением. Жители Припяти, проснувшиеся от хлопка, выходили на балконы. Никто ещё не знал, что это смертельный поток ионизирующего излучения. Природа откликнулась первой: птицы падали с неба, а хвоя в ближайшем лесу почернела за считанные часы.
                </p>
                <p>
                    Эвакуация началась только спустя 36 часов. Громкоговорители объявляли: “В связи с аварией на Чернобыльской АЭС проводится временный выезд... на три дня.” Люди садились в автобусы, уверенные, что вернутся. Но город умер вместе с той ночью.
                </p>
            </section>

            {/* --- Секция 3: Старая Зона и новый саркофаг --- */}
            <section className="lore-section" ref={(el) => (sectionsRef.current[2] = el)}>
                <h2>Старая Зона и новый саркофаг</h2>
                <p>
                    После катастрофы над четвертым блоком нависал поспешно возведенный саркофаг. Он трещал, осыпался, и каждый дождь становился угрозой. В начале XXI века мир снова обратил внимание на Чернобыль: старый саркофаг вот-вот мог рухнуть.
                </p>
                <p>
                    Инженеры и учёные со всей планеты прибыли в Зону, чтобы возвести новый защитный купол. Работы шли в режиме военной дисциплины. Но даже среди грохота машин Зона оставалась собой: рабочие замечали странные огни, слышали помехи в наушниках, а техника иногда отказывала без причин.
                </p>
                <p>
                    В мае 2015 года над старым саркофагом встала огромная арка — новый, сияющий щит. Мир вздохнул с облегчением. Газеты писали: “Чернобыль закрыт. Трагедия окончена.” Но это был лишь новый виток истории.
                </p>
            </section>

            {/* --- Секция 4: Второй взрыв --- */}
            <section className="lore-section" ref={(el) => (sectionsRef.current[3] = el)}>
                <h2>Второй взрыв</h2>
                <p>
                    24 мая 2015 года, через несколько дней после установки саркофага, над Чернобылем раздался гул. В небе открылось багрово-зеленое сияние, а из центра Зоны к небесам поднялся световой столб. Радиоэфир захлебнулся помехами и неразборчивым шепотом.
                </p>
                <p>
                    Когда связь восстановилась, стало ясно: сотни солдат с постов на периметре исчезли. Привычная 30-километровая зона отчуждения перестала существовать. На ее месте возник невидимый купол, а территория внутри удвоилась. Ландшафт переписал сам себя.
                </p>
                <p>
                    Правительства пытались скрыть произошедшее, но это было невозможно. Вокруг нового периметра был создан международный кордон — МСОП (Международные Силы Охраны Периметра). С этого дня стало ясно: Зона родилась заново.
                </p>
            </section>

            {/* --- Секция 5: Новый рубеж --- */}
            <section className="lore-section" ref={(el) => (sectionsRef.current[4] = el)}>
                <h2>Новый рубеж</h2>
                <p>
                    С 2015 по 2022 годы МСОП предпринял десятки попыток проникнуть в Зону, но экспедиции возвращались с потерями или не возвращались вовсе. Выжившие рассказывали об аномальных зонах, где реальность была повреждена, и об артефактах — странных образованиях с невероятными свойствами.
                </p>
                <p>
                    Научные отчеты были полны противоречий. Приборы фиксировали невозможное. В документах всё чаще появлялись слова, больше похожие на мистику, чем на науку: “аномалия”, “энергетический разрыв”.
                </p>
                <p>
                    К 2022 году МСОП впервые удалось закрепиться на первом кордоне. Были возведены блокпосты и лаборатории. Человечество получило точку опоры, но вместе с этим пришло осознание: Зона не просто существует, она меняется и отвечает на каждое вмешательство.
                </p>
            </section>

            {/* --- Секция 6: Зарождение сталкерства --- */}
            <section className="lore-section" ref={(el) => (sectionsRef.current[5] = el)}>
                <h2>Зарождение сталкерства</h2>
                <p>
                    Пока правительства молчали, слухи о Зоне и ее чудесных "артефактах" расползались по миру. В Даркнете появлялись фотографии странных предметов, способных лечить болезни или повышать силу. Это породило новую волну искателей приключений.
                </p>
                <p>
                    Первые одиночки — романтики и безумцы — пробирались вглубь периметра. Почти все они исчезали. Те немногие, кто возвращался, рассказывали о лесах, где деревья дышат, и о существах, сотканных из страха.
                </p>
                <p>
                    МСОП, осознав, что поток не остановить, решил его направить. Из задержанных нарушителей, сумевших выжить в Зоне, были отобраны первые "официальные" сталкеры. Их задачами стали разведка, добыча артефактов и сбор данных под контролем военных. Так началась новая эпоха.
                </p>
            </section>

            {/* --- Секция 7: Сегодняшние дни --- */}
            <section className="lore-section" ref={(el) => (sectionsRef.current[6] = el)}>
                <h2>Сегодняшние дни</h2>
                <p>
                    Прошли годы, но Зона остаётся загадкой. Она живет, дышит и меняется. Снаружи мир делает вид, что всё под контролем, но внутри действуют иные законы. Всё чаще появляются слухи о “движении Зоны”, о том, что она расползается, подбираясь к границам.
                </p>
                <p>
                    МСОП продолжает патрулировать периметр, зная, что за забором начинается иная реальность. И всё же люди тянутся туда. Кто-то верит, что внутри скрыт ответ на главный вопрос, а для кого-то это просто бездна, идущая вглубь самой души.
                </p>
                <p>
                    Сегодняшние дни Зоны — это дни ожидания. Одни считают, что вскоре откроется её “Сердце”. Другие — что она однажды накроет собой весь континент. А есть и те, кто шёпотом говорит: она уже вышла за пределы своих границ и теперь — внутри нас.
                </p>
            </section>
        </main>
    );
}

export default LorePage;